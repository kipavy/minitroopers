// Regenerates tools/oracle/src/data/skills.ts from a $GL clone (read-only data extraction):
//   node tools/oracle/scripts/gen-skills-data.mjs <$GL>/packages/shared/src > tools/oracle/src/data/skills.ts
import { readFileSync } from "node:fs";
import { join } from "node:path";
const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-skills-data.mjs <$GL>/packages/shared/src");
const src = readFileSync(join(dir, "skills.model.ts"), "utf8");
const body = src.slice(src.indexOf("export const Skills = ") + 21, src.indexOf("export const RatSkills"));
const Skills = eval(body.trim().replace(/;$/, ""));
const rat = eval(src.match(/export const RatSkills = (\[[^\]]*\])/)[1]);
const basic = eval(src.match(/export const BasicWeapons = (\[[^\]]*\])/)[1]);
const en = readFileSync(join(dir, "helperSerial/enum.ts"), "utf8");
const sk = en.slice(en.indexOf("class SkillEnum"));
const names = eval(sk.match(/__construct__ = (\[[^\]]*\])/)[1]);
if (names.length !== Skills.length) throw new Error("len");
// sanity: static members index == position
[...sk.matchAll(/static (\w+) = new this\("(\w+)", (\d+)\)/g)].forEach((m, i) => { if (+m[3] !== i || names[i] !== m[1]) throw new Error("order " + m[0]); });
const gen = Skills.map((s) => ({
  w: s.weight, min: s.min, cats: s.cat.map((c) => c[0]),
  open: s.open.map((o) => Skills.findIndex((x) => x.id[1] === o[1])).filter((i) => i !== -1),
}));
let out = `// Derived from minitroopers (Eternaltwin), MIT, Copyright (c) 2026 YesLifeTechnology:
// $GL packages/shared/src/helperSerial/enum.ts (SkillEnum) and packages/shared/src/skills.model.ts
// (Skills weight/min/cat/open, RatSkills, BasicWeapons), $GL commit b06792e. Data only.
// Corpus-generation aid for tools/oracle; the engine's own tables come from the decompiled SWF
// (task 6 asserts SKILL_NAMES equals them). Generated by tools/oracle/scripts/gen-skills-data.mjs.

/** Skill enum constructor names; the array index is the SWF \`Skill\` enum index. */
export const SKILL_NAMES = ${JSON.stringify(names)} as const;

export const SKILL_COUNT = ${names.length};

/** Per skill index: draw weight, minimum level, categories, indexes opened when picked. */
export const SKILL_GEN: readonly { w: number; min: number; cats: readonly string[]; open: readonly number[] }[] = [
${gen.map((g, i) => `  ${JSON.stringify(g).replace(/"(\w+)":/g, "$1: ")}, // ${i} ${names[i]}`).join("\n")}
];

/** $GL RatSkills: skills a mission rat draws 2 of. */
export const RAT_SKILLS = ${JSON.stringify(rat)} as const;

/** $GL BasicWeapons: skill indexes of the starting weapons. */
export const BASIC_WEAPONS = ${JSON.stringify(basic)} as const;
`;
process.stdout.write(out);
